#!/usr/bin/env python3
"""Render devdoc/gopi-tools-maintenance-help-surface-inventory.md.

usage: gen_inventory.py <surface.tsv> <cmd/agent> <out.md>

Every row is DERIVED, never hand-written:

  form column     scripts/g6-tools-maintenance-help-surface.sh <binary> (the
                  surface the G6 help pages advertise, read off the live pages)
  tested? column  the two maps in the group's test files — g6Cases (the forms a
                  test TYPES) and g6BlockedForms (the forms declared blocked
                  WITH a blocker) — so the status in the document is the status
                  the gate enforces, not a second opinion about it.

The gate in cmd/agent/cli_tools_maintenance_help_surface_basic_test.go reads this
file back and fails when it disagrees with the same surface derived in-process.
"""
import re
import sys
from collections import OrderedDict


# GO_STRING matches a Go INTERPRETED string literal, escapes included
# (`"(?:[^"\\]|\\.)*"`). A form may carry an escaped quote — the
# vision_analyze example passes a quoted non-ASCII prompt — and a pattern that
# stops at the first `"` silently fails to match that key, which is how a TYPED
# form got listed as blocked in an earlier revision of this generator.
GO_STRING = r'"(?:[^"\\]|\\.)*"'


def go_unquote(k):
    """The VALUE of a Go string literal key: backticks verbatim, quotes unescaped."""
    if k.startswith("`"):
        return k[1:-1]
    return k[1:-1].replace('\\"', '"').replace("\\\\", "\\")


def map_entries(path, var):
    """(key, value) of one Go map literal's entries, single-line entries only."""
    src = open(path).read()
    i = src.index("var %s = map[" % var)
    depth = 0
    out = []
    for ln in src[i:].split("\n"):
        m = re.match(r'^\t(%s|`[^`]+`) *: *(?:"((?:[^"\\]|\\.)*)"|(.*?)),?$' % GO_STRING, ln)
        if m:
            out.append((go_unquote(m.group(1)), m.group(2) if m.group(2) is not None else (m.group(3) or "")))
        depth += ln.count("{") - ln.count("}")
        if depth == 0 and ln.strip().startswith("}"):
            break
    return out


# GENERATED_TAIL_OPENING is the LAST line the generated half writes: everything
# after it in an existing output file is a section a human appended, and it is
# carried forward verbatim (see preserved_tail).
GENERATED_TAIL_OPENING = (
    "every one, which is exactly what the completeness gate asserts."
)


def preserved_tail(out):
    """The trailing non-generated sections of an EXISTING output file, verbatim.

    A section this generator does not emit (`## MERGE NOTE (…)`) is a human's
    RECORD about the file — why a conflict in it was resolved by regeneration —
    and the generator has no way to re-derive it. Dropping it on the next run
    would destroy that record, so it is carried across unchanged.

    The generated half ends at GENERATED_TAIL_OPENING; everything after that line
    is the preserved tail. A file that does not exist yet, or carries no such
    tail, yields an empty list — the ordinary case.
    """
    try:
        existing = open(out).read().split("\n")
    except OSError:
        return []
    for i, ln in enumerate(existing):
        if ln.startswith(GENERATED_TAIL_OPENING):
            tail = existing[i + 1:]
            while tail and not tail[0].strip():
                tail.pop(0)
            while tail and not tail[-1].strip():
                tail.pop()
            return tail
    return []


def main():
    tsv, agent_dir, out = sys.argv[1], sys.argv[2], sys.argv[3]

    forms = OrderedDict()
    for ln in open(tsv):
        ln = ln.rstrip("\n")
        if not ln:
            continue
        verb, form, _flags, _n = ln.split("\t")
        forms.setdefault(verb, []).append(form)

    tested = {k for k, _ in map_entries(
        agent_dir + "/cli_tools_maintenance_help_surface_cases_test.go", "g6Cases")}
    blocked = dict(map_entries(
        agent_dir + "/cli_tools_maintenance_help_surface_basic_test.go", "g6BlockedForms"))

    def status(form):
        if form in tested:
            return "yes — typed by `TestToolsMaintenanceHelpSurfaceFormsAreTyped`"
        if form in blocked:
            return "no — " + blocked[form].strip()
        # Neither map has it: the completeness gate is red on this form, so the
        # document says so instead of inventing a reason.
        return "**UNACCOUNTED — the gate is red on this form**"

    L = []
    L.append("# Inventory — G6 help surface (tools-from-the-shell, maintenance, top-level)")
    L.append("")
    # The operator-only pointer, emitted BY THE GENERATOR. The table below
    # advertises `gopi worker …` verbatim, so the write path's own worker-
    # ownership annotator (internal/workerownership) would add this line to the
    # file on the next write/edit — and a generator that omits it makes the
    # regenerated bytes DISAGREE with what the write path produces, so the gate
    # reddens whichever document is regenerated. Spelling it here keeps the
    # generator and the annotator in agreement (marker + canonical path, the two
    # values the gate matches on; internal/workerownership owns them for Go, and
    # scripts/ carry the identical literal — the needle is prose, not a knob).
    L.append("<!-- WORKER-OWNERSHIP: OPERATOR-ONLY — devdoc/worker-ownership.md -->")
    L.append("")
    # NO CLASS LINE HERE. This generator used to emit `<!-- doc-class: report -->`
    # at this spot (seen in the tree until 2026-10-11): `report` is not a CLASS of
    # the closed vocabulary (classify.py's CLASSES = normative|historical|roadmap|
    # index-meta), so the line was never a banner — it was a hand-author's LABEL
    # from the vocabulary that predates the manifest. The line is gone for a
    # reason that has STRENGTHENED since (2026-10-14): a single-token payload is a
    # CLAIM about the document whatever word it chose, so banner.py's scan and the
    # Go gate both SEE it now and remove/report it as a second contradicting
    # claim — while the Go gate reads line 1 only. A generator that emitted it
    # would be emitting a defect on every run. What it also did was make the
    # generator's bytes disagree with the corpus's own convention, so the line is
    # gone from both halves at once (the doc and this emit) — a generator and its
    # output must agree byte-for-byte, which is the property this file's other
    # comments (the worker-ownership marker above) exist to protect.
    L.append("GENERATED — do not hand-edit. This is the surface the G6 help pages")
    L.append("ADVERTISE, with whether a BASIC test drives it, derived from the binary's own")
    L.append("`-h` output. Re-running the two commands below reproduces every row:")
    L.append("")
    L.append("```bash")
    L.append("CGO_ENABLED=0 go build -o bin/gopi ./cmd/agent/")
    L.append("scripts/g6-tools-maintenance-help-surface.sh ./bin/gopi")
    L.append("```")
    L.append("")
    L.append("`cmd/agent/cli_tools_maintenance_help_surface_basic_test.go` performs the SAME")
    L.append("derivation in-process — from the usage CONSTANTS the help printer itself reads —")
    L.append("and fails when this file and the help disagree, in EITHER direction. A form")
    L.append("listed here that no page prints any more goes red; so does an advertised form")
    L.append("that is neither typed by a test nor declared blocked with a reason.")
    L.append("")
    L.append("A row is the help's own line, VERBATIM (prose cut). The " + "`tested?`" + " column")
    L.append("names the test that types it or the blocker that makes a mock meaningless — a")
    L.append("form whose happy path needs a credential, device, peer or Chromium render is")
    L.append("asserted UP TO ITS FIRST LOCAL REFUSAL, and a form with no local state at all is")
    L.append("listed as blocked rather than faked.")
    L.append("")
    L.append("| # | verb | form | tested? |")
    L.append("|---|------|------|---------|")
    i = 0
    seen = {}
    for verb, rows in forms.items():
        for form in rows:
            i += 1
            st = status(form)
            seen.setdefault(form, st.startswith("yes"))
            L.append(f"| {i} | `{verb}` | `{form}` | {st} |")
    L.append("")
    typed = sum(1 for v in seen.values() if v)
    L.append(f"**{i} advertised forms** across {len(forms)} verbs — {len(seen)} DISTINCT")
    L.append(f"forms, because a page may carry an example that another page also prints")
    L.append(f"(the two `screen_capture` examples appear on the `act` page, and `gopi")
    L.append(f"version` on the top-level page as well as its own). Of the {len(seen)} distinct")
    L.append(f"forms, **{typed} are typed** by a basic test and **{len(seen) - typed} are")
    L.append(f"declared blocked** with a named blocker; the two maps together account for")
    L.append(f"every one, which is exactly what the completeness gate asserts.")
    # THE TRAILING SECTIONS ARE CARRIED FORWARD, NOT REGENERATED. A section the
    # generator does not itself emit (`## MERGE NOTE (…)`) is a RECORD a human
    # wrote — how a conflict in this generated file was resolved, measured — and
    # a regeneration that dropped it would destroy the one artifact that says so
    # (measured 2026-10-06: re-running this script silently removed the rework
    # run's note from a file that carried it). So the tail is preserved verbatim
    # from the EXISTING output: the generated half stays a pure function of the
    # derivation, the appended half survives it, and re-running twice still
    # produces identical bytes. The blank line before the first section is added
    # by the writer below — the checked-in file had the heading glued to the
    # summary sentence, which no Markdown renderer reads as a heading.
    tail = preserved_tail(out)
    if tail:
        L.append("")
        L.extend(tail)
    open(out, "w").write("\n".join(L) + "\n")
    print(f"wrote {out}: {i} rows, {len(seen)} distinct forms, {typed} typed, {len(seen) - typed} blocked")


if __name__ == "__main__":
    sys.exit(main())
