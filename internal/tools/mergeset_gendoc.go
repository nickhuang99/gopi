package tools

// mergeset_gendoc.go — THE UNION HALF of the published-anchor edge, wired into
// the MERGED-RESULT measurement (rebuild_vet_mergeset.go).
//
// THE DEFECT this file closes, in the words of whoever next reads the branch.
// A document of record publishes `path/file.go:NNN` anchors (COMMANDS.md
// publishes 54 of them). Insert a line above such a function and the published
// line number is WRONG — the document must be regenerated. (The check that
// blames the drift used to be internal/standards' TestCommandsDoc*, deleted with
// internal/docclass in 5a35f61; what runs TODAY is this file's own merge lane
// reading the published anchors, plus `go run
// internal/standards/testdata/commands-census.go . COMMANDS.md --check`.) So the
// delivery point asks the published-
// anchor edge about the branch's OWN change (task_finish_gendoc.go) and runs
// the packages it names.
//
// THAT QUESTION IS MEASURED OVER ONE DIFF, AND A LANDING IS NOT ONE DIFF. The
// delivery point measures `git diff --name-only <ref>...<branch>` — the MERGE
// BASE to the branch tip, deliberately, so another branch's commit is never
// attributed to this one. Two concurrently delivered branches can therefore
// each be internally consistent — each one's own document matches its own
// source — while the tree the landing composes has never been generated by
// anyone. Measured on this repo 2026-10-12: commits 03f2d1dfe (07:40),
// 93e402d36 (13:28) and 721268925 (16:18) each moved
// `cmd/agent/cli_doccheck.go`'s routing predicate (118 → 152 → 161 → 194) and
// each left COMMANDS.md untouched; the master they were merged into carried
// `cli_doccheck.go:161` in the document and `:194` in the source.
//
// WHY HERE AND NOT A NEW HOOK (Rule 3/35 — no new tool, no new script, no new
// resident dependency). The merged-result measurement already exists and
// already runs on every landing (`RebuildAfterMergeMergeset`, reached from
// RebuildAfterMerge's close loop, `gopi task merge`'s tail and the merger pass)
// — and its revision IS the union. Its scope is already "the landing's own
// diff", (read the same way `<mergeRev>^ <mergeRev>`), so the union half is the
// SAME measurement with one more member in the membership test. Nothing ticks,
// and nothing else has to be remembered.
//
// WHAT IT ADDS TO THE RUN SET:
//
//	② the paths the LANDING brought in (`<mergeRev>^ <mergeRev>`);
//	③ the paths the FIRST PARENT brought in (`<parent1>^ <parent1>`);
//	④ the paths the SECOND PARENT brought in (`<parent2>^ <parent2>`) — the two
//	   parent legs are what make a path that moved NO anchor inside its own
//	   branch visible: branch A edits an anchor source and regenerates the
//	   document, branch B's own change is elsewhere, and only the union shows
//	   both halves at once;
//	⑤ the document ITSELF — dropped as an entry, kept as a FLAG. This one makes
//	   the compound case work without asking the edge a question its contract
//	   cannot answer. The edge maps a change onto the ANCHOR SOURCES a document
//	   publishes; a landing that only touched the document obliges nothing by
//	   that rule — yet if it ALSO brought in a commit that moved one of those
//	   sources, the tree it left behind carries a document nobody regenerated.
//	   So the document is dropped from `changedFiles` (asking the edge about a
//	   document would be asking it to judge a generated file, a question it does
//	   not answer) and read as a FLAG: the gates of EVERY participating edge run
//	   when the landing touched the document.
//
// THE HONEST LIMIT, stated so a later reader does not mistake a known gap for a
// check that covers it: a commit that moved a published anchor source WITHOUT
// touching the document is visible HERE only when it arrives IN the landing or
// in one of the landing's two parents. A commit further back on master is a
// pre-existing state — and THAT half is the sibling leg's, not a silence:
// mergeset_gendoc_base.go measures the BASE revision's tree with the same edge
// and the same run set, so the drift this membership test cannot see is reported
// by name against the revision that carries it (the same reason a red the base
// already carried is not blamed on the landing).
//
// NEVER A REPAIR, NEVER A ROLLBACK. It does not run the generator (rewriting
// the document is the author's act, not a gate's), never hand-edits the
// generated block, and its red is REPORTED through the merged-result step's own
// channels (notify + bug row, deduped by defect identity) with `res.OK` left
// alone — the sibling step's contract, unchanged.
//
// IT REUSES, IT DOES NOT RE-DECLARE. The edge (internal/gendoc) is the one
// definition of what a change obliges; the toolchain argv, the gate-package
// suffix, the two-dot diff verb and the run/parse/attribute machinery are the
// merged-result step's (Rule 14 — one rendering). What lives here is only what
// is genuinely new: the union membership test and the document flag.

import (
	"context"
	"fmt"
	"sort"
	"strings"

	"github.com/nick/gopi/internal/config"
	"github.com/nick/gopi/internal/gendoc"
)

// gendocUnionGateName is how this step identifies itself in every message. It is
// deliberately neither vetGateName NOR mergesetGateTestGateLabel: those are the
// module-wide check and the package-scope map, and an operator reading a
// close-out line has to be able to tell which of the three asked for the run
// (Rule 1b: compared and reported, so named once).
const gendocUnionGateName = "published-anchors"

// gendocErrorClassSkipEnv is the OPERATOR's documented escape for the
// published-anchor ERROR class — the one hole that no package a tree could run
// can close (a root document whose generator lives under testdata/ derives NO
// gate package in principle, so a line moved under its anchors is caught by
// nobody).
//
// It is deliberately NOT a tree property, NOT a settings key and NOT something a
// branch can set for itself: the class exists because a hole in the guard was
// found, and the only legitimate reason to retire it on a tree is a human's
// decision about that tree. Setting it empties Answer.Errors — the
// published-anchor class alone — and never Answer.Findings, so the broken edges
// that were refusals before this class existed are not switchable here.
//
// It is a PRIVILEGE, not a bypass: every arm that honours it SAYS SO in its own
// sentence (see gendocErrorClassSkipNote), so a tree that is being merged with
// the class retired is visibly being merged with it retired rather than looking
// like a clean land (Rule 15). The reader is gendocErrorClassSkipped, and it is
// the only one (Rule 2: the constant is the default and exactly ONE place reads
// the environment).
const gendocErrorClassSkipEnv = "GOPI_GENDOC_ERROR_CLASS_SKIP"

// gendocErrorClassSkipped reports whether this process has retired the
// published-anchor ERROR class. It is the ONE reader of
// gendocErrorClassSkipEnv, through the config funnel every other boolean env var
// in this package goes through.
func gendocErrorClassSkipped() bool { return config.EnvBool(gendocErrorClassSkipEnv) }

// gendocErrorClassSkipNote is the sentence an arm APPENDS when it is running
// with the class retired. Empty when the class is live, so a clean land reads
// exactly as it read before.
func gendocErrorClassSkipNote() string {
	if !gendocErrorClassSkipped() {
		return ""
	}
	return " (" + gendocErrorClassSkipEnv + " is set: the published-anchor ERROR class is retired for this run)"
}

// gendocUnionScratchPattern names this step's scratch checkouts inside the
// merged-result step's own scratch class, so a crashed run leaves the residue
// the sweeper already knows how to take (Rule 35: no new root, no new reaper).
const gendocUnionScratchPattern = "mergeset-union-"

// gendocUnionSecondParent is the merge commit's second parent — the tip of the
// branch that was landed, which is the other half of the union. It is a REVISION
// SUFFIX, never a revision on its own: the suffix is COMPOSED ONTO A REAL PARENT
// SHA (see mergesetGendocParentRev), which is the only way to name the Nth
// parent of a commit. git has no `<rev>N` parent syntax at all — `<rev>2` is
// `<rev>` followed by a PATH — so `<mergeRev>2` resolves nothing on any landing.
// That is the defect this file carried: the leg composed the suffix onto the
// merge rev itself, EVERY landing's rev-parse failed, and the root-commit
// tolerance swallowed the failure — half the union contributed no path, with
// every test green (Rule 15).
const gendocUnionSecondParent = "2"

// The two parent legs' NAMES, spelled once each: they are what a note and a log
// line call the leg, and a reader of a close-out has to be able to tell which
// half of the union was read (Rule 1b).
const (
	gendocUnionFirstParentLabel  = "first-parent"
	gendocUnionSecondParentLabel = "second-parent"
)

// The git spellings the parent legs are read with. The parent list is read ONCE
// per landing, in ONE call, so the two legs cannot disagree about the commit's
// shape and each leg's parent is INDEXED out of git's own output rather than
// asked for with its own revision expression — which is what makes the read's
// success independent of how many parents the commit happens to have.
const (
	gendocUnionParentsVerb      = "rev-list"
	gendocUnionParentsFlag      = "--parents"
	gendocUnionParentsCountFlag = "-n"
	gendocUnionParentsCountOne  = "1"
	// gendocUnionRootBoundaryNote marks a leg whose parent is the repository's
	// ROOT commit: the leg was read and had no preceding state to measure, which
	// is a boundary of the history rather than a leg that failed.
	gendocUnionRootBoundaryNote = " (the repository's root: no preceding state)"
	// mergesetGatePairLabel names the pairs the parent legs are diffed over
	// (`<a>^ <a>`), so the reason a pair failed to resolve says WHICH read it
	// was rather than leaving a reader to infer it from the revisions alone.
	mergesetGendocPairLabel = "two-dot pair"
)

// gendocUnionPathLimit bounds the union this step will hand the edge, so a
// pathological landing (a vendored tree imported in one commit) cannot turn one
// close-out into an unbounded walk. Exceeding it is REPORTED and the check
// abstains — never a silent widening, never a silent pass (Rule 15).
const gendocUnionPathLimit = 20000

// mergesetGendocRuns answers the union question for one landing and returns the
// runs to append to the caller's run set, plus ONE log-ready note.
//
// A note is returned for every outcome that OBSERVED something, and its own
// words carry the distinction a reader needs: "nothing was obliged" and "the
// union could not be measured" are different facts (Rule 15), and the second is
// an abstention that must never read as a clean pass.
//
// dir is the landing's own detached checkout, owned by the caller for the
// lifetime of this call: the question is asked OF THE COMMIT, never of whatever
// directory the merger happens to stand in — the merged-result step's own
// premise. An empty dir is a caller error, not an abstention to hide: the
// caller materialises the revision before it asks anything.
func mergesetGendocRuns(ctx context.Context, repo, mergeRev, dir string) ([]mergesetGateRun, string) {
	if dir == "" {
		return nil, "the union question was asked without the landing's checkout — the answer would be about a directory rather than about the commit (recorded, not measured)"
	}
	union, documentTouched, readLegs, note := mergesetGendocUnion(ctx, repo, mergeRev)
	if note != "" {
		return nil, note
	}
	// The legs that READ are part of every note this step produces when the
	// union obliges nothing: "the union covers no anchor source" and "one half of
	// the union was never read" are different facts, and the second is the shape
	// of a defect this file has already carried once (Rule 15).
	legs := gendocUnionLegsReadNote(readLegs)
	// ONE READ OF THE TREE (Rule 14): the answer carries the participation
	// classification, the requirements and the broken-edge findings together.
	ans, err := gendoc.GeneratedDocAnswer(dir, union)
	if err != nil {
		return nil, "the published-anchor edge could not be read (" + mergeBuildGateTail(err.Error()) + ")"
	}
	if !ans.TakesPart() {
		// A tree that publishes no generated document takes part in no edge: an
		// abstention stated with the counts the SAME walk produced, so "the scan
		// found nothing" is never inferred from silence (Rule 15).
		reason := ans.Reason
		if reason == "" {
			reason = gendoc.ParticipationUnknown
		}
		return nil, fmt.Sprintf(
			"this tree publishes no generated document, so it takes part in no published-anchor edge (%d candidate(s), %d edge(s)): %s%s",
			ans.Candidates, ans.Docs, reason, legs)
	}
	if len(ans.Findings) > 0 || len(ans.Errors) > 0 {
		// A BROKEN EDGE IS REPORTED, never read as "nothing to run" (Rule 15): a
		// document whose generator is not in the tree, an edge with no gate
		// package, or an edge defect NO package could catch (the ERROR class) is
		// an instruction a reader would follow into a command that runs nothing.
		//
		// The ERROR class is joined into the SAME sentence on purpose: this step
		// is the merged-result REPORT (Rule 12 — no verdict rides it), and a
		// class that reached it and was not printed would be a measurement
		// nobody sees. The REFUSAL on that class is the delivering branch's own
		// arm (`finishCleanupBranchAnchorCheck`), which refuses before the merge
		// is even attempted.
		return nil, "the published-anchor edge is BROKEN — " +
			strings.Join(append(append([]string(nil), ans.Errors...), ans.Findings...), mergeCheckAbstainSeparator)
	}
	required := append([]string(nil), ans.Required...)
	if documentTouched && len(required) == 0 {
		// The landing touched the document of record and the edge obliged
		// nothing: the gates of every PARTICIPATING edge run, because "is the
		// document in step with the sources this landing changed?" is precisely
		// the question they answer.
		required = mergesetGendocParticipationGates(dir)
		if len(required) == 0 {
			return nil, "the landing touched the document of record, but no gate package reads it — nothing blocks on this document (recorded, not silently passed)"
		}
	}
	if len(required) == 0 {
		return nil, fmt.Sprintf(
			"the landing's union touches no published anchor source (%d path(s) measured%s) — nothing to re-run", len(union), legs)
	}
	refs := mergesetGendocPackageRefs(required)
	return []mergesetGateRun{{
		Gate:     gendocUnionGateName,
		Argv:     append(mergesetGateTestArgv(), refs...),
		Packages: refs,
	}}, ""
}

// gendocUnionLegsReadNote renders the parent legs that READ as a parenthetical
// for a note, so a reader can tell a union that OBSERVED both halves from one
// that silently carried a single half. A leg that did not read has already been
// reported as its own note by mergesetGendocUnion (it is not a silence), so
// naming the ones that did is the positive half of the same statement.
func gendocUnionLegsReadNote(readLegs []string) string {
	if len(readLegs) == 0 {
		return "; no parent leg could be read"
	}
	return "; parent leg(s) read: " + strings.Join(readLegs, ", ")
}

// mergesetGendocParticipationGates names the gate packages of every edge this
// tree has, read through the edge's OWN exported surface (Rule 14: one reader of
// the tree, never a second opinion about which documents participate).
func mergesetGendocParticipationGates(dir string) []string {
	deps, err := gendoc.Deps(dir)
	if err != nil {
		return nil
	}
	var out []string
	for _, dep := range deps {
		out = append(out, dep.GatePackages...)
	}
	return gendocDedupSorted(out)
}

// mergesetGendocPackageRefs renders the edge's DIRECTORY answers as the runnable
// package arguments the toolchain takes, de-duplicated and sorted so the run
// list is reproducible. The rendering is the delivery-point consumer's ("./" +
// directory); it is spelled here through the one suffix constant rather than a
// second literal (Rule 1b).
func mergesetGendocPackageRefs(dirs []string) []string {
	refs := make([]string, 0, len(dirs))
	for _, d := range dirs {
		refs = append(refs, "."+mergesetGatePackageSep+d)
	}
	return gendocDedupSorted(refs)
}

// mergesetGendocUnionLeg is ONE parent leg of the union question. The label is
// what a note and a log line call the leg (Rule 1b — a reader must be able to
// tell WHICH half of the union was read), and the index is that leg's position
// in git's own parent list (`rev-list --parents` order), so "the first-parent
// leg" and "parent[0]" cannot drift apart.
type mergesetGendocUnionLeg struct {
	label string
	index int
}

// gendocUnionLegs names the union's parent legs, in the order they are read: the
// landing's FIRST parent (master before the landing) and its SECOND parent (the
// branch tip that was landed). The second leg is the one the defect killed, so
// its index is stated literally once, here, as the leg's own identity.
func gendocUnionLegs() []mergesetGendocUnionLeg {
	return []mergesetGendocUnionLeg{
		{label: gendocUnionFirstParentLabel, index: 0},
		{label: gendocUnionSecondParentLabel, index: 1},
	}
}

// mergesetGendocUnion resolves the union of paths one landing brings into
// master, plus the document-touched flag, plus the parent legs that READ (the
// caller reports them when the union obliges nothing — see mergesetGendocRuns).
//
// A non-empty note means the union could not be measured AT ALL — the landing's
// own diff did not resolve, or the union exceeded its bound. A parent leg that
// cannot be read is NOT that (the union stays measurable from the landing's own
// diff), but it is still REPORTED — as its own entry in `notes` AND in the
// log — because the difference between "the union covers this" and "this leg was
// not read" must never have to be inferred (Rule 15).
//
// THE POSITIVE ARMS ARE NOT THE SAME FACT, and they must never share one
// `continue`. Three shapes are separated, two of them facts about the COMMIT and
// one of them a DEFECT:
//
//   - the commit HAS fewer parents than this leg names (a root commit has none):
//     a fact, read from the parent LIST'S LENGTH, not from a failed expression;
//   - the parent IS the repository's root: it has no preceding state to differ
//     from, so the leg added nothing — a BOUNDARY, stated rather than inferred
//     from a `git diff` that failed (this was the second instance of the same
//     swallowed failure, and the pre-fix code ate it too);
//   - the read FAILED — rev-list refused, the parent object is unreadable, or
//     the pair did not diff — which is a defect in this step's own
//     instrumentation and is reported as a DEFECT naming the leg.
//
// Before this split the whole second-parent leg asked `<mergeRev>2` (git's parent
// syntax is `<rev>^N`; `<rev>2` is a PATH — measured: `git rev-parse c504b41de2`
// exits 128 and echoes the argument, and so does `<root>^`), and because a failed
// read and an absent parent both landed in the same `continue`, half the union
// contributed no path on every landing and no operator ever saw a line about it.
//
// Every read is TWO-DOT (`<a>^ <a>`), deliberately NOT the delivery point's
// three-dot form: three-dot measures from the merge base, which is exactly what
// a landing's union must not do — the whole defect is the change OUTSIDE the
// merge base.
func mergesetGendocUnion(ctx context.Context, repo, mergeRev string) (union []string, documentTouched bool, readLegs []string, note string) {
	seen := map[string]bool{}
	var notes []string
	landed, reason := mergesetGendocDiffLabeled(ctx, repo, mergeRev+mergesetGateFirstParent, mergeRev, mergesetGendocPairLabel)
	if reason != "" {
		return nil, false, nil, "the landing's own diff could not be resolved, so its union is unknown (" + reason + ")"
	}
	for _, p := range landed {
		seen[p] = true
	}
	parents, parentsReason := mergesetGendocParents(repo, mergeRev)
	switch {
	case parentsReason != "":
		// The commit's SHAPE is unreadable: no parent leg can be read, and that
		// is reported as itself (never as "this landing has no parents").
		leg := gendocUnionParentsNote(mergeRev, parentsReason)
		mergesetGateLog("%s", leg)
		notes = append(notes, leg)
	default:
		for _, l := range gendocUnionLegs() {
			if l.index >= len(parents) {
				// The commit HAS fewer parents than this leg names — a fact
				// about the commit (a root commit has none), not a failure.
				continue
			}
			parent := parents[l.index]
			// The leg asks what ITS parent brought in, which is read as the
			// parent's own diff base (`<parent>^ <parent>`) — and that base does
			// not exist when the parent IS the repository's root commit. A root
			// has no preceding state to differ from, so it added nothing and
			// the leg is read as a BOUNDARY: stated, contributing no path, and
			// never confused with a leg that failed to read (the distinction is
			// decided by the parent's OWN parent list, not by the failure of a
			// revision expression — see mergesetGendocParents).
			own, ownReason := mergesetGendocParents(repo, parent)
			switch {
			case ownReason != "":
				leg := "the union's " + l.label + " leg (parent " + parent + " of " + mergeRev + ") was NOT read: " + ownReason
				mergesetGateLog("%s", leg)
				notes = append(notes, leg)
				continue
			case len(own) == 0:
				readLegs = append(readLegs, l.label+" "+parent+gendocUnionRootBoundaryNote)
				continue
			}
			paths, preason := mergesetGendocDiffLabeled(ctx, repo, parent+mergesetGateFirstParent, parent, l.label)
			if preason != "" {
				leg := "the union's " + l.label + " leg (parent " + parent + " of " + mergeRev + ") was NOT read: " + preason
				mergesetGateLog("%s", leg)
				notes = append(notes, leg)
				continue
			}
			readLegs = append(readLegs, l.label+" "+parent)
			for _, p := range paths {
				seen[p] = true
			}
		}
	}
	union = make([]string, 0, len(seen))
	for p := range seen {
		union = append(union, p)
	}
	union = gendocDedupSorted(union)
	if len(union) > gendocUnionPathLimit {
		return nil, false, readLegs, fmt.Sprintf(
			"the landing's union holds %d path(s), over this step's bound of %d — the published-anchor question was NOT asked of it (recorded, not measured)",
			len(union), gendocUnionPathLimit)
	}
	// The document flag is decided over the SAME change set the union was built
	// from (never a second read that could disagree with it): the document is
	// dropped as an entry by the caller of the edge, and its touch is a flag.
	for _, p := range union {
		if gendoc.IsCandidateDocument(p) {
			documentTouched = true
			break
		}
	}
	if len(notes) > 0 {
		note = strings.Join(notes, mergeCheckAbstainSeparator)
	}
	return union, documentTouched, readLegs, note
}

// mergesetGendocParents lists a commit's parents in git's own order, and states
// in its own words when the LIST could not be read at all.
//
// The read is the commit's shape rather than a revision expression, and that is
// deliberate: `git rev-parse <rev>^N` reports a missing parent and a broken
// revision expression with the SAME exit status and the SAME echoed argument
// (measured on this host: `<root>^`, `<root>^2` and `<rev>2` all exit 128 and
// print the argument back), so an error there cannot be turned into a statement
// about the commit. `rev-list --parents` can: it SUCCEEDS whenever it can read
// the commit, and what it prints IS the parent list — so an absence is read from
// the list's LENGTH and every failure is a genuine failure to read.
func mergesetGendocParents(repo, rev string) (parents []string, reason string) {
	out, err := repoSweepGit(repo, gendocUnionParentsVerb, gendocUnionParentsFlag,
		gendocUnionParentsCountFlag, gendocUnionParentsCountOne, rev)
	if err != nil {
		return nil, "git " + gendocUnionParentsVerb + " " + gendocUnionParentsFlag + " " + rev + " failed (" + mergeBuildGateTail(err.Error()) + ")"
	}
	fields := strings.Fields(out)
	if len(fields) == 0 {
		return nil, "git " + gendocUnionParentsVerb + " " + gendocUnionParentsFlag + " " + rev + " printed nothing — the commit's shape is unknown"
	}
	// fields[0] is the commit itself; the rest are its parents, in order.
	return fields[1:], ""
}

// gendocUnionParentsNote states an unreadable commit shape as this step's own
// note, so the caller abstains with a sentence naming what could not be read.
func gendocUnionParentsNote(rev, reason string) string {
	return "the union's parent legs could not be read at all for " + rev + ": " + reason
}

// mergesetGendocDiffLabeled is mergesetGendocDiff with the READ named, so a
// failure to resolve a revision pair says which leg it was (the unlabeled form
// is kept for callers whose read has exactly one possible meaning).
func mergesetGendocDiffLabeled(ctx context.Context, repo, from, to, label string) (paths []string, reason string) {
	paths, reason = mergesetGendocDiff(ctx, repo, from, to)
	if reason == "" {
		return paths, ""
	}
	return nil, label + ": " + reason
}

// mergesetGendocDiff lists the paths one revision pair touched, and states in
// its own words when the pair cannot be read at all.
func mergesetGendocDiff(ctx context.Context, repo, from, to string) (paths []string, reason string) {
	out, err := repoSweepGit(repo, mergesetGateDiffVerb, mergesetGateNameOnlyFlag, from, to)
	if err != nil {
		return nil, "git diff --name-only " + from + " " + to + ": " + mergeBuildGateTail(err.Error())
	}
	for _, line := range strings.Split(out, "\n") {
		if p := strings.TrimSpace(line); p != "" {
			paths = append(paths, p)
		}
	}
	return paths, ""
}

// gendocUnionMaterialise checks rev out into dir and reports whether it is
// there. The shape lives in ONE place so a test fixture and the step cannot
// drift about what "the landing's tree" means.
func gendocUnionMaterialise(repo, dir, rev string) (string, bool) {
	if _, err := repoSweepGit(repo, mergeBuildGateWorktreeVerb, mergeBuildGateWorktreeAddVerb,
		mergeBuildGateWorktreeDetachFlag, dir, rev); err != nil {
		return "", false
	}
	return rev, true
}

// gendocDedupSorted sorts and de-duplicates a path list. The edge's own copy is
// unexported, and re-implementing `sort` here rather than re-exporting it keeps
// the two packages independent (internal/tools may not import an unexported
// helper, and exporting one for a cosmetic reason would widen the edge's
// surface).
func gendocDedupSorted(values []string) []string {
	seen := map[string]bool{}
	out := make([]string, 0, len(values))
	for _, v := range values {
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	sort.Strings(out)
	return out
}
