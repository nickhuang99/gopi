// peer_self_host_test.go — the MINIMAL REPRO of the self-peer profile leak
// (measured 2026-10-08, master 087f506df, task 01a117c9-1111) and the
// regression guard for its fix (Rule 5: every fix ships the smallest test
// that reproduced the defect).
//
// WHAT THE DEFECT WAS. `gopi task send --peer <alias>` with no `--remote-home`,
// where the alias resolves to THIS host, spawns the peer-side handler through
// `ssh` and lets the LOCAL login shell decide its profile — so the row lands in
// the OPERATOR's ledger. Measured four fixture rows, two dispatched as real
// work.
//
// THE FIXTURE IS THE MECHANISM'S TWO HALVES, and both must be REAL or the test
// proves nothing:
//
//	① the alias RESOLVES to this host — a generated ssh config with
//	   `Host <alias> / HostName <this host's address>`, read through the file
//	   the predicate actually consults (HOME is pinned to it, so this is not a
//	   simulation of the resolution: it IS the resolution);
//	② the leg carries NO --remote-home, and the exchange closure performs what
//	   the ssh hop performs — switch to the profile the peer's OWN environment
//	   resolves, then run the REAL handler (SyncRowRemote). That profile is a
//	   private temp file standing in for the production destination, which was
//	   the operator's real `~/.gopi/memory.db`.
//
// WHY THE OPERATOR LEDGER IS MEASURED IN THE REPORT AND NOT HERE. A test that
// resolved — let alone wrote — `~/.gopi/memory.db` would BE the defect this task
// is about, and the ledger is append-only, so a test that "proved" the leak by
// reproducing it there would leave a permanent fixture row behind. The fixture
// reproduces the leak's SHAPE and asserts on COUNTS; the real file is measured
// once, read-only, by the real-binary sandbox run in `devdoc/self-peer-write-refusal.md`.
//
// EVERY ASSERTION IS A CRASH CASE. The positive arm asserts the peer's
// unbound-profile ledger stays EMPTY and that the peer was never contacted, so it
// FAILS BY COUNTING, exactly as the incident presented itself (a row that should
// not exist). The negative arms keep the refusal from becoming collateral damage:
// a real remote alias still sends, and a same-host alias WITH --remote-home still
// sends — the designed way to run a same-host leg, read back out of the BOUND
// profile's ledger.

