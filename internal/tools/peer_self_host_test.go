const (
	// selfPeerLocalAlias is the generated alias that RESOLVES to this host.
	selfPeerLocalAlias = "gopi-selfpeer-probe"
	// selfPeerRemoteAlias is the generated alias that resolves to ANOTHER
	// host — the ordinary deployment the fix must not touch.
	selfPeerRemoteAlias = "gopi-selfpeer-remote"
	// selfPeerRemoteAddr is an address guaranteed absent from this host's own
	// interface set (TEST-NET-1, RFC 5737: reserved for documentation and
	// never assigned to an interface).
	selfPeerRemoteAddr = "192.0.2.7"
	// selfPeerTestRow is the row the send leg ships.
	selfPeerTestRow = "t-selfpeer-01"
)

// selfPeerConfigHome writes an ssh config carrying TWO stanzas — the alias that
// resolves to this host and the alias that does not — and pins HOME to it for
// the duration of the test, so selfPeerResolvedHost reads exactly this file.
//
// (HOME is what locates ssh's own config, and config.GopiHome follows GOPI_HOME
// when that is set — so GOPI_HOME must be unset here, which is also the
// production shape of a caller that never sandboxed itself at that level.)
func selfPeerConfigHome(t *testing.T) string {
	t.Helper()
	home := t.TempDir()
	if err := os.MkdirAll(filepath.Join(home, selfPeerSSHDirName), 0o755); err != nil {
		t.Fatalf("create ssh dir: %v", err)
	}
	local, err := selfPeerTestLocalAddr(t)
	if err != nil {
		t.Fatalf("resolve this host's own address for the fixture: %v", err)
	}
	cfg := "# generated by peer_self_host_test.go\n" +
		"Host " + selfPeerLocalAlias + "\n  HostName " + local + "\n\n" +
		"Host " + selfPeerRemoteAlias + "\n  HostName " + selfPeerRemoteAddr + "\n"
	if err := os.WriteFile(filepath.Join(home, selfPeerSSHDirName, selfPeerSSHConfigName), []byte(cfg), 0o600); err != nil {
		t.Fatalf("write ssh config: %v", err)
	}
	t.Setenv("HOME", home)
	return home
}

// selfPeerTestLocalAddr returns ONE address this host really answers to, read
// from the predicate's own measurement (never a literal in the test): the
// fixture must be the measured fact, not a copy of it.
func selfPeerTestLocalAddr(t *testing.T) (string, error) {
	t.Helper()
	for addr := range selfPeerLocalAddrs() {
		return addr, nil
	}
	return "", os.ErrNotExist
}

// selfPeerRefusalLedgerFixture points THIS process at a ledger that RESOLVES to
// the operator's own file, and returns that resolved path.
//
// The trick is the profile ROOT: config.GopiDir is `<GOPI_HOME>/.gopi`, and the
// operator's own ledger is `<operator home>/.gopi/memory.db`. Pinning
// GOPI_HOME=<temp> and GOPI_MEMORY_DB=<temp>/.gopi/memory.db therefore makes
// memoryDBPath() return EXACTLY the string the leak writes, while the file
// itself is a private temp path — no test writes the real profile, and the
// assertion is on the identity the GATE compares, never on a copy of it.
//
// (The directory name is composed here from config.ProfileDirName /
// config.MemoryDBFileName, so a rename of either moves the fixture with it.)
func selfPeerRefusalLedgerFixture(t *testing.T) string {
	t.Helper()
	base := t.TempDir()
	t.Setenv(config.GopiDirEnv, base)
	ledger := filepath.Join(base, config.ProfileDirName, config.MemoryDBFileName)
	t.Setenv(config.MemoryDBEnv, ledger)
	return ledger
}

// selfPeerLedgerRowCount counts the rows a given ledger file holds, opening it
// through the ledger's OWN initializer. It returns 0 for a file that does not
// exist yet — which is itself information here: a ledger nothing ever wrote is
// a ledger with no rows, and the fix's assertion is "this number did not grow".
func selfPeerLedgerRowCount(t *testing.T, path string) int {
	t.Helper()
	db, err := openTasksDB(context.Background(), path)
	if err != nil {
		t.Fatalf("open ledger %s: %v", path, err)
	}
	defer db.Close()
	var n int
	if err := db.QueryRow(`SELECT COUNT(*) FROM tasks`).Scan(&n); err != nil {
		t.Fatalf("count rows in %s: %v", path, err)
	}
	return n
}

// TestSelfPeerSendIsRefusedAndTheOperatorResolvedLedgerGainsNoRow is THE repro.
//
// It drives the REAL surface (SyncRowSendEx, the primitive behind `gopi task
// send`) with the REAL config-file resolution, and asserts the three things the
// incident needed:
//
//	① the leg returns a refusal naming the alias and the way out (exit non-zero
//	   arrives at the CLI as this error);
//	② the refusal carries the family's sentinel (errors.Is) — so a caller can
//	   tell a topology refusal from a transport failure;
//	③ THE PEER PROCESS IS NEVER SPAWNED (contacted stays false), and the ledger
//	   an unbound peer-side handler would resolve stays EMPTY.
//
// WHY ③ IS COUNTED IN A SEPARATE FILE. The leak's effect is "a PEER process
// wrote a profile nobody chose" — so the instrument must be the ledger THAT
// process resolves, not the caller's. The exchange closure therefore performs
// what the ssh hop performs (switch this process to the peer's own profile, run
// the REAL handler `SyncRowRemote`), against a private temp profile standing in
// for "whatever the login shell resolves". BEFORE the fix that closure RUNS and
// the file gains the row; after it, the gate stops the leg before any contact
// and the file stays empty. (The production instance of that file was the
// operator's real `~/.gopi/memory.db` — which is why the harness must never
// point at it: the fixture reproduces the SHAPE, and the real-binary sandbox run
// in this task's report carries the operator-ledger measurement, read-only.)
func TestSelfPeerSendIsRefusedAndTheOperatorResolvedLedgerGainsNoRow(t *testing.T) {
	selfPeerConfigHome(t)
	ledger := selfPeerRefusalLedgerFixture(t)
	t.Setenv(config.SyncPeersEnv, selfPeerLocalAlias)
	config.ResetNodeIdentityForTest()
	t.Cleanup(config.ResetNodeIdentityForTest)

	// The row that WOULD travel: queued here, so the leg's own gates (id
	// resolution, status, dependency) all pass and the self-peer gate is the
	// ONLY thing standing between this call and the write.
	seedSelfPeerRow(t, selfPeerTestRow, ledger)
	before := selfPeerLedgerRowCount(t, ledger)
	if before == 0 {
		t.Fatalf("fixture: the row was not seeded, so the count assertion below proves nothing")
	}

	// The ledger an UNBOUND peer-side process resolves — the leak's destination.
	peerProfile := t.TempDir()
	peerLedger := filepath.Join(peerProfile, config.ProfileDirName, config.MemoryDBFileName)

	contacted := false
	_, err := SyncRowSendEx(SyncRowSendOptions{
		TaskID: selfPeerTestRow,
		CancelSource: true, // a send IS a move (epic task-send-is-a-move)
		Peers:  []string{selfPeerLocalAlias},
		Exchange: func(peer string, body []byte) ([]byte, error) {
			contacted = true
			// What the ssh hop does when no --remote-home binds it: the peer
			// handler runs with the profile ITS OWN environment resolves.
			restoreHome := testutil.SnapshotEnv(t, config.GopiDirEnv)
			restoreDB := testutil.SnapshotEnv(t, config.MemoryDBEnv)
			// env-leak-ok: a PER-CALL profile flip (Rule 17's reviewed shape) — the
			// peer's environment must be restored when THIS leg returns, not at test
			// cleanup.
			if serr := os.Setenv(config.GopiDirEnv, peerProfile); serr != nil { //stylegate:ignore the scope is ONE peer leg, not the test: the value must be gone when this closure returns, while t.Setenv's undo would ride t.Cleanup to the end and leave a later leg pointing at the peer's profile
				t.Fatalf("pin the unbound peer profile: %v", serr)
			}
			// env-leak-ok: same per-call unwind as above.
			if uerr := os.Unsetenv(config.MemoryDBEnv); uerr != nil { //stylegate:ignore same per-call scope: the unbound peer resolves its ledger from its own GOPI_HOME, and the caller's explicit --db must not leak into it
				t.Fatalf("clear the db env for the peer side: %v", uerr)
			}
			out, herr := SyncRowRemote(body)
			restoreDB()
			restoreHome()
			return out, herr
		},
	})
	if err == nil {
		t.Fatalf("BUG: a self-peer send with no --remote-home was accepted — the peer leg runs in the profile this caller resolves, which is how fixture rows reached the operator's ledger")
	}
	if !errors.Is(err, errSelfPeerWrite) {
		t.Fatalf("the refusal does not carry the family sentinel: %v", err)
	}
	for _, want := range []string{selfPeerLocalAlias, SyncRowRemoteHomeFlagName, "resolves to"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("the refusal must name %q (alias, the way out, the evidence): %v", want, err)
		}
	}
	if contacted {
		t.Fatalf("the refusal reached the peer: a gate must refuse BEFORE any contact, not after — the peer process is the thing whose profile nobody bound")
	}
	if got := selfPeerLedgerRowCount(t, peerLedger); got != 0 {
		t.Fatalf("THE LEAK: the peer's unbound profile gained %d row(s) — a self-peer send wrote a ledger its caller never chose", got)
	}
	if after := selfPeerLedgerRowCount(t, ledger); after != before {
		t.Fatalf("the caller's own ledger changed (%d → %d) on a REFUSED send: a refusal must write nothing", before, after)
	}
}

// TestSelfPeerSendStillWorksWithRemoteHome is the designed way to run a
// same-host leg, and it must KEEP working: `--remote-home DIR` binds the peer
// side's profile, which is the whole point of the flag. The leg is accepted, the
// exchange runs, and the row lands in the BOUND profile rather than in the
// caller's.
func TestSelfPeerSendStillWorksWithRemoteHome(t *testing.T) {
	selfPeerConfigHome(t)
	callerLedger := selfPeerRefusalLedgerFixture(t)
	t.Setenv(config.SyncPeersEnv, selfPeerLocalAlias)
	config.ResetNodeIdentityForTest()
	t.Cleanup(config.ResetNodeIdentityForTest)
	seedSelfPeerRow(t, selfPeerTestRow, callerLedger)
	before := selfPeerLedgerRowCount(t, callerLedger)

	peerRoot := t.TempDir() // the peer's private profile root (GOPI_HOME on the peer side)
	contacted := false
	lines, err := SyncRowSend(SyncRowSendOptions{
		TaskID:     selfPeerTestRow,
		CancelSource: true, // a send IS a move (epic task-send-is-a-move)
		Peers:      []string{selfPeerLocalAlias},
		RemoteHome: peerRoot,
		Exchange: func(peer string, body []byte) ([]byte, error) {
			contacted = true
			// What the ssh prefix does on the peer side: GOPI_HOME=<dir>.
			restoreHome := testutil.SnapshotEnv(t, config.GopiDirEnv)
			restoreDB := testutil.SnapshotEnv(t, config.MemoryDBEnv)
			// env-leak-ok: a PER-CALL profile flip (Rule 17's reviewed shape); the value
			// must be gone when this leg returns, restored via testutil.SnapshotEnv.
			if err := os.Setenv(config.GopiDirEnv, peerRoot); err != nil { //stylegate:ignore the scope is ONE peer leg, not the test — t.Setenv's undo would ride t.Cleanup past every subsequent leg
				t.Fatalf("pin peer profile: %v", err)
			}
			// env-leak-ok: same per-call unwind as above.
			if err := os.Unsetenv(config.MemoryDBEnv); err != nil { //stylegate:ignore same per-call scope: the peer resolves its ledger from GOPI_HOME, and the caller's --db must not leak into it
				t.Fatalf("clear db env for the peer side: %v", err)
			}
			out, herr := SyncRowRemote(body)
			restoreDB()
			restoreHome()
			return out, herr
		},
	})
	if err != nil {
		t.Fatalf("a same-host send WITH --remote-home must still work: %v", err)
	}
	if !contacted || len(lines) != 1 {
		t.Fatalf("contacted=%v lines=%v — the bound leg must reach the peer", contacted, lines)
	}
	if after := selfPeerLedgerRowCount(t, callerLedger); after != before {
		t.Fatalf("binding --remote-home must keep the CALLER's ledger untouched: %d → %d", before, after)
	}
	// THE REAL PROOF: the row is in the BOUND profile's ledger, read back
	// through the ledger's own opener — never inferred from the receipt.
	peerLedger := filepath.Join(peerRoot, config.ProfileDirName, config.MemoryDBFileName)
	if got := selfPeerLedgerRowCount(t, peerLedger); got == 0 {
		t.Fatalf("the row did not land in the bound profile %s (the receipt said %v)", peerLedger, lines)
	}
}

// TestRemotePeerSendIsNotTouchedByTheSelfPeerGate is the no-collateral arm: an
// alias resolving to ANOTHER host is the ordinary deployment, and the gate must
// be invisible to it — same call, same ledger, no --remote-home, accepted.
func TestRemotePeerSendIsNotTouchedByTheSelfPeerGate(t *testing.T) {
	selfPeerConfigHome(t)
	callerLedger := selfPeerRefusalLedgerFixture(t)
	t.Setenv(config.SyncPeersEnv, selfPeerRemoteAlias)
	config.ResetNodeIdentityForTest()
	t.Cleanup(config.ResetNodeIdentityForTest)
	seedSelfPeerRow(t, selfPeerTestRow, callerLedger)

	contacted := false
	lines, err := SyncRowSend(SyncRowSendOptions{
		TaskID: selfPeerTestRow,
		CancelSource: true, // a send IS a move (epic task-send-is-a-move)
		Peers:  []string{selfPeerRemoteAlias},
		Exchange: func(peer string, body []byte) ([]byte, error) {
			contacted = true
			return SyncRowRemote(body) // the peer's own profile answers, as in production
		},
	})
	if err != nil {
		t.Fatalf("a REMOTE peer must not be refused by the self-peer gate: %v", err)
	}
	if !contacted {
		t.Fatalf("the ordinary deployment did not reach its peer")
	}
	if len(lines) != 1 {
		t.Fatalf("want one receipt line, got %v", lines)
	}
}

// TestSelfPeerGateDoesNotFireWhenTheLedgerIsAlreadyPrivate pins the arm that
// keeps the gate from firing on a caller who already isolated itself: the peer
// alias still resolves here, but the CALLER's ledger is not the operator's, so
// the write the gate exists to stop cannot reach the caller's ledger at all.
//
// It asserts the SAME outcome as the repro from the opposite direction — the
// caller's private ledger's count is unchanged while the leg proceeds — which is
// what distinguishes "isolated" from "leaking" (a distinction the whole fix
// turns on, and one that a naive "refuse every self-peer" would collapse).
func TestSelfPeerGateDoesNotFireWhenTheLedgerIsAlreadyPrivate(t *testing.T) {
	selfPeerConfigHome(t)
	t.Setenv(config.GopiDirEnv, t.TempDir()) // a caller in its OWN profile, not the operator's
	t.Setenv(config.MemoryDBEnv, testutil.NewTestDBPath(t))
	t.Setenv(config.SyncPeersEnv, selfPeerLocalAlias)
	config.ResetNodeIdentityForTest()
	t.Cleanup(config.ResetNodeIdentityForTest)

	ledger := memoryDBPath()
	seedSelfPeerRow(t, selfPeerTestRow, ledger)
	before := selfPeerLedgerRowCount(t, ledger)

	contacted := false
	_, err := SyncRowSendEx(SyncRowSendOptions{
		TaskID: selfPeerTestRow,
		CancelSource: true, // a send IS a move (epic task-send-is-a-move)
		Peers:  []string{selfPeerLocalAlias},
		Exchange: func(peer string, body []byte) ([]byte, error) {
			contacted = true
			return SyncRowRemote(body)
		},
	})
	// THE ONLY REQUIREMENT HERE IS THE CALLER'S LEDGER: an isolated caller may
	// be refused or allowed (both answers are defensible for a self-peer), but
	// the row must never be counted in the ledger the caller is working from
	// through a peer leg it did not bind.
	if after := selfPeerLedgerRowCount(t, ledger); after != before {
		t.Fatalf("an unbound self-peer leg wrote the caller's own ledger: %d → %d (contacted=%v err=%v)", before, after, contacted, err)
	}
}

// seedSelfPeerRow writes ONE pending row into the given ledger, through the
// ledger's own writer, so the send leg's other gates see a row it would
// genuinely ship.
func seedSelfPeerRow(t *testing.T, id, ledger string) {
	t.Helper()
	restoreDB := testutil.SnapshotEnv(t, config.MemoryDBEnv)
	// env-leak-ok: a PER-CALL ledger flip (Rule 17's reviewed shape), restored
	// below through testutil.SnapshotEnv.
	if err := os.Setenv(config.MemoryDBEnv, ledger); err != nil { //stylegate:ignore the scope is ONE seeding step, not the test — the value must be restored before the leg under test runs
		t.Fatalf("pin ledger %s: %v", ledger, err)
	}
	if _, err := TaskNewOID(TaskNewOptions{
		Summary: "self-peer probe row",
		TaskID:  id,
		Payload: "the row a self-peer leg would ship",
		Source:  "human",
	}); err != nil {
		t.Fatalf("seed row: %v", err)
	}
	rowLegForceStatus(t, id, TaskStatusPending, float64(time.Now().Unix()))
	restoreDB()
}

// TestSelfPeerTransferTakeOverIsRefusedBeforeTheOffer is the SECOND gated
// surface's own repro: the takeover round's step (SIGN) writes on the PEER — it
// CASes the row pending -> cancelled there — so a self-peer alias runs that write
// in the profile the local login shell resolves, exactly as the send leg does.
// The gate is asked BEFORE the round's first contact, so a refused round is a
// provable no-op rather than a half-read that dies at the sign.
//
// RED BEFORE THE FIX, and in either of the two ways the defect can present: the
// round either ACCEPTED the self-peer (no error at all — it proceeded to the
// offer and returned an empty result, which is how a fixture-row transfer starts)
// or it failed in the TRANSPORT, where the error does not carry this family's
// sentinel. The assertion below is the sentinel, so both shapes are red.
func TestSelfPeerTransferTakeOverIsRefusedBeforeTheOffer(t *testing.T) {
	selfPeerConfigHome(t)
	selfPeerRefusalLedgerFixture(t)
	t.Setenv(config.SyncPeersEnv, selfPeerLocalAlias)
	config.ResetNodeIdentityForTest()
	t.Cleanup(config.ResetNodeIdentityForTest)

	_, err := SyncTransferTakeOver(SyncTransferTakeOverOptions{Peer: selfPeerLocalAlias})
	if err == nil {
		t.Fatalf("BUG: a self-peer takeover round was accepted — its SIGN step writes the peer's ledger in a profile the caller never chose")
	}
	if !errors.Is(err, errSelfPeerWrite) {
		t.Fatalf("the round did not refuse by the self-peer gate (a transport failure is not the same refusal): %v", err)
	}
	if !strings.Contains(err.Error(), "transfer") || !strings.Contains(err.Error(), selfPeerLocalAlias) {
		t.Errorf("the refusal must name the leg and the alias: %v", err)
	}
}
